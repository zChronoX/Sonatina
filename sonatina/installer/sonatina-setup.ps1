# Sonatina installer helper (called by SonatinaSetup.exe, runs elevated).
#   -ListAdapters -Out file       USB Bluetooth adapters: "VID|PID|state|name" per line
#                                 state = windows (used by Windows) | winusb (already dedicated)
#   -BindAdapter -Vid -Pid -Wdi   give the adapter to Sonatina (WinUSB via libwdi wdi-simple)
#   -RestoreAdapter               give the adapter back to Windows (reads HKLM\Software\Sonatina)
#   -HasVBCable                   exit 0 when VB-CABLE is installed, 1 otherwise
#   -InstallVBCable               download VB-CABLE from vb-audio.com and run its setup
#   -StopAll                      stop any running Sonatina (installed or development build)
param(
    [switch]$ListAdapters, [string]$Out,
    [switch]$BindAdapter, [string]$Vid, [string]$ProductId, [string]$Wdi,
    [switch]$RestoreAdapter,
    [switch]$HasVBCable,
    [switch]$InstallVBCable,
    [switch]$StopAll,
    [string]$Log = (Join-Path $env:TEMP 'sonatina-setup.log')
)
$ErrorActionPreference = 'Continue'

function Write-Log([string]$text) {
    $line = "$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') $text"
    Add-Content -Path $Log -Value $line -Encoding UTF8
    Write-Host $line
}

function Get-UsbBluetoothAdapters {
    $result = @()
    foreach ($d in Get-PnpDevice -PresentOnly -ErrorAction SilentlyContinue) {
        # whole USB devices only (no composite interfaces "&MI_xx")
        if ($d.InstanceId -notmatch '^USB\\VID_([0-9A-F]{4})&PID_([0-9A-F]{4})\\') { continue }
        $v = $Matches[1]; $p = $Matches[2]
        $compat = (Get-PnpDeviceProperty -InstanceId $d.InstanceId -KeyName 'DEVPKEY_Device_CompatibleIds' `
                   -ErrorAction SilentlyContinue).Data
        $isBt = ($d.Class -eq 'Bluetooth') -or ($compat -match 'USB\\Class_E0&SubClass_01&Prot_01')
        if (-not $isBt) { continue }
        $state = if ($d.Service -eq 'WinUSB') { 'winusb' } else { 'windows' }
        $name = ($d.FriendlyName -replace '\|', '/')
        $result += [pscustomobject]@{ Vid = $v; Pid = $p; State = $state; Name = $name; InstanceId = $d.InstanceId }
    }
    return $result
}

function Remove-LibwdiPackages([string]$v, [string]$p) {
    $hwid = "VID_$v&PID_$p"
    foreach ($pkg in Get-WindowsDriver -Online -All -ErrorAction SilentlyContinue |
             Where-Object { $_.ProviderName -eq 'libwdi' }) {
        $details = Get-WindowsDriver -Online -Driver $pkg.Driver -ErrorAction SilentlyContinue
        if (($details | ForEach-Object { $_.HardwareId }) -match [regex]::Escape($hwid)) {
            Write-Log "removing WinUSB package $($pkg.Driver) for $hwid"
            pnputil /delete-driver $pkg.Driver /uninstall /force | Out-String | Write-Log
        }
    }
    foreach ($store in 'Cert:\LocalMachine\Root', 'Cert:\LocalMachine\TrustedPublisher') {
        Get-ChildItem $store | Where-Object { $_.Subject -like "*VID_$v&PID_$p (libwdi autogenerated)*" } |
            ForEach-Object { Write-Log "removing certificate $($_.Subject) from $store"; Remove-Item $_.PSPath }
    }
    pnputil /scan-devices | Out-Null
}

if ($ListAdapters) {
    $lines = Get-UsbBluetoothAdapters | ForEach-Object { "$($_.Vid)|$($_.Pid)|$($_.State)|$($_.Name)" }
    if ($Out) { Set-Content -Path $Out -Value $lines -Encoding Ascii } else { $lines }
    exit 0
}

if ($BindAdapter) {
    $current = Get-UsbBluetoothAdapters | Where-Object { $_.Vid -eq $Vid -and $_.Pid -eq $ProductId }
    if ($current -and $current.State -eq 'winusb') { Write-Log "adapter $Vid`:$ProductId already on WinUSB"; exit 0 }
    $dest = Join-Path $env:TEMP 'sonatina-winusb'
    Write-Log "binding WinUSB to $Vid`:$ProductId with $Wdi"
    $out = & $Wdi --name 'Sonatina Bluetooth adapter' --manufacturer 'Sonatina' `
        --vid "0x$Vid" --pid "0x$ProductId" --type 0 --dest $dest --timeout 120000 2>&1 | Out-String
    $code = $LASTEXITCODE
    Write-Log $out
    Write-Log "wdi-simple exit code $code"
    exit $code
}

if ($RestoreAdapter) {
    $key = 'HKLM:\Software\Sonatina'
    $v = (Get-ItemProperty $key -ErrorAction SilentlyContinue).AdapterVid
    $p = (Get-ItemProperty $key -ErrorAction SilentlyContinue).AdapterPid
    if (-not $v -or -not $p) { Write-Log "no adapter recorded"; exit 0 }
    Remove-LibwdiPackages $v $p
    Write-Log "adapter $v`:$p given back to Windows"
    exit 0
}

if ($HasVBCable) {
    $cable = Get-PnpDevice -Class MEDIA -ErrorAction SilentlyContinue |
        Where-Object { $_.FriendlyName -like '*VB-Audio Virtual Cable*' -and $_.Status -eq 'OK' }
    if ($cable) { exit 0 } else { exit 1 }
}

if ($InstallVBCable) {
    $work = Join-Path $env:TEMP 'sonatina-vbcable'
    New-Item -ItemType Directory -Force $work | Out-Null
    $zip = Join-Path $work 'vbcable.zip'
    $ok = $false
    foreach ($n in 46, 45, 47, 48) {
        $url = "https://download.vb-audio.com/Download_CABLE/VBCABLE_Driver_Pack$n.zip"
        try {
            Write-Log "downloading $url"
            Invoke-WebRequest -Uri $url -OutFile $zip -UseBasicParsing -ErrorAction Stop
            $ok = $true; break
        } catch { Write-Log "  failed: $($_.Exception.Message)" }
    }
    if (-not $ok) {
        Write-Log "VB-CABLE download failed: opening the official page"
        Start-Process 'https://vb-audio.com/Cable/'
        exit 2
    }
    Expand-Archive -Path $zip -DestinationPath $work -Force
    $setup = Get-ChildItem $work -Recurse -Filter 'VBCABLE_Setup_x64.exe' | Select-Object -First 1
    if (-not $setup) { Write-Log "VBCABLE_Setup_x64.exe not found in the package"; exit 3 }
    Write-Log "running $($setup.FullName) (click 'Install Driver')"
    $proc = Start-Process -FilePath $setup.FullName -WorkingDirectory $setup.DirectoryName -PassThru -Wait
    Write-Log "VB-CABLE setup exit code $($proc.ExitCode)"
    exit 0
}

if ($StopAll) {
    Get-CimInstance Win32_Process -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -eq 'Sonatina.exe' -or
                       (($_.Name -eq 'pythonw.exe' -or $_.Name -eq 'python.exe') -and
                        ($_.CommandLine -like '*sonatina_tray.py*' -or $_.CommandLine -like '*sonatina_host.py*')) } |
        ForEach-Object { Write-Log "stopping $($_.Name) PID $($_.ProcessId)"; Stop-Process -Id $_.ProcessId -Force }
    exit 0
}

Write-Host "nothing to do (see the header of this script)"
